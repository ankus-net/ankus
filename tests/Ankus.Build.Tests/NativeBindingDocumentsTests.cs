using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Ankus.Build.Tests;

/// <summary>
/// Verifies the small documents that let Go to Definition open a generated declaration from the companion's PDB.
/// </summary>
/// <param name="context">The test's cancellation context.</param>
[TestClass]
public sealed class NativeBindingDocumentsTests(TestContext context)
{
    private const string Preamble = "// <auto-generated/>\n#nullable enable\nnamespace Ankus.Postgres;\n\n";

    private const string Source = Preamble + """
        // ankus-document: Point.g.cs
        /// <summary>
        /// A point.
        /// </summary>
        public struct Point
        {
            /// <summary>
            /// The horizontal position.
            /// </summary>
            public int X;
        }

        // ankus-document: Calls.g.cs
        /// <summary>
        /// Calls.
        /// </summary>
        public static partial class Calls
        {
        // ankus-member: Calls.First.g.cs
            /// <summary>
            /// Returns one.
            /// </summary>
            public static int First() => 1;

        // ankus-member: Calls.Second.g.cs
            /// <summary>
            /// Returns two.
            /// </summary>
            public static int Second()
            {
                return 2;
            }

        // ankus-end
        }

        // ankus-document: Mode.g.cs
        /// <summary>
        /// A mode.
        /// </summary>
        public enum Mode
        {
            /// <summary>
            /// The only mode.
            /// </summary>
            Only,
        }

        """;

    /// <summary>
    /// Types compile from their own documents, and a class's members compile in one declaration mapped to theirs.
    /// </summary>
    [TestMethod]
    public void TypesAndMembersHaveTheirOwnDocuments()
    {
        NativeBindingDocumentLayout layout = NativeBindingDocuments.Split(Source);
        Assert.AreSequenceEqual<string>(["documents/Point.g.cs", "members/Calls.g.cs", "documents/Mode.g.cs"],
            layout.Compiled.Select(static document => document.Path));
        Assert.AreSequenceEqual<string>(["documents/Point.g.cs", "documents/Calls.g.cs", "documents/Calls.First.g.cs", "documents/Calls.Second.g.cs",
            "documents/Mode.g.cs"], layout.Embedded.Select(static document => document.Path));
        Assert.AreEqual(layout.Embedded[0], layout.Compiled[0]);
        Assert.AreEqual(Preamble + "/// <summary>\n/// Calls.\n/// </summary>\npublic static partial class Calls\n{\n}\n\n",
            layout.Embedded[1].Text);
        Assert.AreEqual(Preamble + "public static partial class Calls\n{\n    /// <summary>\n    /// Returns one.\n    /// </summary>\n" +
            "    public static int First() => 1;\n\n}\n", layout.Embedded[2].Text);
        Assert.AreSequenceEqual<string>(["documents/Point.g.cs", "documents/Calls.g.cs", "documents/Calls.First.g.cs", "documents/Calls.Second.g.cs",
            "documents/Mode.g.cs", "members/Calls.g.cs"], layout.Files.Select(static document => document.Path));

        // Each document compiles on its own, as an editor compiles the documents it opens from a PDB.
        foreach (NativeBindingDocument document in layout.Embedded)
        {
            Assert.IsEmpty(Compile([document]).GetDiagnostics(context.CancellationToken), document.Path);
        }

        // Every compiled line maps to the identical line of the document it came from.
        CSharpCompilation compilation = Compile(layout.Compiled);
        Assert.IsEmpty(compilation.GetDiagnostics(context.CancellationToken));
        var documents = layout.Embedded.ToDictionary(static document => "../" + document.Path, static document => document.Text.Split('\n'));
        SyntaxTree members = compilation.SyntaxTrees.Single(static tree => tree.FilePath == "members/Calls.g.cs");
        Microsoft.CodeAnalysis.Text.SourceText text = members.GetText(context.CancellationToken);
        int mapped = 0;
        foreach (Microsoft.CodeAnalysis.Text.TextLine line in text.Lines.Skip(Lines(Preamble)))
        {
            string content = line.ToString();
            if (content.StartsWith("#line", StringComparison.Ordinal) || line.Span.IsEmpty && line.End == text.Length)
            {
                continue;
            }

            FileLinePositionSpan span = members.GetMappedLineSpan(line.Span, context.CancellationToken);
            Assert.IsTrue(span.HasMappedPath, content);
            Assert.AreEqual(documents[span.Path][span.StartLinePosition.Line], content, $"line {line.LineNumber + 1}");
            mapped++;
        }

        // Five header lines, five and eight member lines and two closing lines; each member's wrapper is not compiled.
        Assert.AreEqual(20, mapped);

        MethodDeclarationSyntax second = compilation.SyntaxTrees.SelectMany(tree => tree.GetRoot(context.CancellationToken).DescendantNodes())
            .OfType<MethodDeclarationSyntax>().Single(static method => method.Identifier.Text == "Second");
        FileLinePositionSpan location = second.Identifier.GetLocation().GetMappedLineSpan();
        Assert.AreEqual("../documents/Calls.Second.g.cs", location.Path);
        Assert.Contains("public static int Second()", documents[location.Path][location.StartLinePosition.Line]);
    }

    /// <summary>
    /// The layout reads source with either line ending, and source without markers compiles as before.
    /// </summary>
    [TestMethod]
    public void LineEndingsAndUnmarkedSourceKeepTheirMeaning()
    {
        NativeBindingDocumentLayout crlf = NativeBindingDocuments.Split(Source.ReplaceLineEndings("\r\n"));
        NativeBindingDocumentLayout lf = NativeBindingDocuments.Split(Source);
        Assert.AreSequenceEqual(lf.Compiled, crlf.Compiled);
        Assert.AreSequenceEqual(lf.Embedded, crlf.Embedded);
        NativeBindingDocumentLayout unmarked = NativeBindingDocuments.Split("public static class Probe\n{\n}\n");
        Assert.AreEqual(new NativeBindingDocument("native-binding.g.cs", "public static class Probe\n{\n}\n"), Assert.ContainsSingle(unmarked.Compiled));
        Assert.IsEmpty(unmarked.Embedded);

        // A marker must start its line, so the same text elsewhere is ordinary source.
        string quoted = "public static class Probe\n{\n    // see // ankus-document: Probe.g.cs\n}\n";
        Assert.AreEqual(quoted, Assert.ContainsSingle(NativeBindingDocuments.Split(quoted).Compiled).Text);
    }

    /// <summary>
    /// A class without members, such as a companion that selects no functions, keeps its closing lines in its own document.
    /// </summary>
    [TestMethod]
    public void ClassesWithoutMembersStayWhole()
    {
        const string Empty = Preamble + "// ankus-document: Calls.g.cs\npublic static partial class Calls\n{\n// ankus-end\n}\n\n" +
            "// ankus-document: Point.g.cs\npublic struct Point;\n";
        NativeBindingDocumentLayout layout = NativeBindingDocuments.Split(Empty);
        NativeBindingDocument calls = new("documents/Calls.g.cs", Preamble + "public static partial class Calls\n{\n}\n\n");
        Assert.AreSequenceEqual([calls, new("documents/Point.g.cs", Preamble + "public struct Point;\n")], layout.Compiled);
        Assert.AreSequenceEqual(layout.Compiled, layout.Embedded);
        Assert.ThrowsExactly<FormatException>(() => NativeBindingDocuments.Split(Empty.Replace("\n}\n\n//", "\n}\n// ankus-member: Calls.Late.g.cs\n\n//",
            StringComparison.Ordinal)));
    }

    /// <summary>
    /// Malformed or ambiguous layouts fail instead of compiling declarations into the wrong documents.
    /// </summary>
    /// <param name="source">The marked source after the preamble.</param>
    [TestMethod]
    [DataRow("// ankus-member: Calls.First.g.cs\npublic static int First() => 1;\n")]
    [DataRow("// ankus-document: Calls.g.cs\npublic static partial class Calls\n{\n// ankus-member: Calls.First.g.cs\n}\n// ankus-document: Other.g.cs\n")]
    [DataRow("// ankus-end\n}\n")]
    [DataRow("// ankus-document: Point.g.cs\npublic struct Point;\n// ankus-end\n}\n")]
    [DataRow("// ankus-document: Calls.g.cs\npublic static partial class Calls\n{\n// ankus-member: Calls.First.g.cs\n")]
    [DataRow("// ankus-document: Point.g.cs\npublic struct Point;\n// ankus-member: Point.X.g.cs\n")]
    [DataRow("// ankus-document: Point.g.cs\n// ankus-document: point.g.cs\n")]
    [DataRow("// ankus-document: ../Point.g.cs\n")]
    [DataRow("// ankus-document: Point.cs\n")]
    [DataRow("// ankus-document: NUL.g.cs\n")]
    [DataRow("// ankus-document: Point.g.cs")]
    public void MalformedLayoutsAreRejected(string source)
        => Assert.ThrowsExactly<FormatException>(() => NativeBindingDocuments.Split(Preamble + source));

    /// <summary>
    /// Document names are valid on every supported file system and stay distinct where case does not count.
    /// </summary>
    [TestMethod]
    public void NamesAreValidOnEveryFileSystem()
    {
        var used = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        Assert.AreEqual("Node.g.cs", NativeBindingDocuments.Name(used, "Node"));
        Assert.AreEqual("node_2.g.cs", NativeBindingDocuments.Name(used, "node"));
        Assert.AreEqual("NODE_3.g.cs", NativeBindingDocuments.Name(used, "NODE"));
        Assert.AreEqual("CON_.g.cs", NativeBindingDocuments.Name(used, "CON"));
        Assert.AreEqual("lpt1_.g.cs", NativeBindingDocuments.Name(used, "lpt1"));
        Assert.AreEqual("NativeMethods.aux.g.cs", NativeBindingDocuments.Name(used, "NativeMethods.aux"));
        string prefix = "NativeMethods." + new string('x', 120);
        string first = NativeBindingDocuments.Name(used, prefix + "_first");
        string second = NativeBindingDocuments.Name(used, prefix + "_second");
        Assert.AreNotEqual(first, second);
        Assert.AreEqual(96 + ".g.cs".Length, first.Length);
        Assert.StartsWith(prefix[..70], first);
        foreach (string invalid in new[] { "", "1abc", "a-b", "a..b", "a.", ".a", "é", "a/b" })
        {
            Assert.ThrowsExactly<FormatException>(() => NativeBindingDocuments.Name(used, invalid), invalid);
        }
    }

    private CSharpCompilation Compile(IEnumerable<NativeBindingDocument> documents)
        => CSharpCompilation.Create("Layout", documents.Select(document =>
            CSharpSyntaxTree.ParseText(document.Text, path: document.Path, cancellationToken: context.CancellationToken)),
            CompilationReferences.Platform, new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary,
                nullableContextOptions: NullableContextOptions.Enable, generalDiagnosticOption: ReportDiagnostic.Error));

    private static int Lines(string text) => text.Count(static character => character == '\n');
}
