using System.Diagnostics;
using System.Text.RegularExpressions;
using Ankus.PgConfig;

namespace Ankus.Build;

/// <summary>
/// Builds the modules that let PostgreSQL load an extension's output plugin under other names, as pglogical's
/// <c>pglogical_output</c> module forwards to <c>pglogical</c>.
/// </summary>
/// <remarks>
/// PostgreSQL finds an output plugin by its library's filename. Each alias module is a small C library that loads the
/// extension's library and forwards <c>_PG_output_plugin_init</c> to it, compiled with the compiler and PostgreSQL
/// headers that built the extension's native boundary.
/// </remarks>
internal static partial class OutputPluginAliasCommand
{
    /// <summary>
    /// Builds every alias module into the publish directory and lists their filenames for the publication manifest.
    /// </summary>
    /// <param name="arguments">
    /// Artifact directory, publish directory, extension library filename, PostgreSQL major, <c>pg_config</c> path or an
    /// empty string, compiler path, semicolon-separated library directories, target triple or an empty string, and the
    /// alias list file.
    /// </param>
    /// <param name="cancellationToken">Cancels compilation.</param>
    /// <returns>A task that completes after every module is built.</returns>
    internal static async Task RunAsync(string[] arguments, CancellationToken cancellationToken = default)
    {
        if (arguments.Length != 9)
        {
            throw new ArgumentException("Expected artifact directory, publish directory, library, PostgreSQL major, pg_config path, compiler, " +
                "library directories, target triple and alias list.", nameof(arguments));
        }

        string artifacts = Path.GetFullPath(arguments[0]);
        string output = Path.GetFullPath(arguments[1]);
        string library = arguments[2];
        string[] aliases = [.. File.ReadAllLines(arguments[8]).Where(static line => line.Length > 0).Distinct(StringComparer.Ordinal)];
        string target = Path.GetFileNameWithoutExtension(library);
        string extension = Path.GetExtension(library);
        string[] modules = [.. aliases.Select(alias => alias + extension)];

        // The library's name goes into the generated C as a string literal.
        if (!AliasName().IsMatch(target))
        {
            throw new ArgumentException($"Library '{library}' needs a plain filename to have output plugin aliases.", nameof(arguments));
        }

        foreach (string alias in aliases)
        {
            if (!AliasName().IsMatch(alias) || string.Equals(alias, target, StringComparison.OrdinalIgnoreCase))
            {
                throw new ArgumentException($"'{alias}' is not a valid output plugin alias for library '{library}'.", nameof(arguments));
            }
        }

        // The list is always rewritten, so a later publish without aliases does not keep listing old modules.
        await File.WriteAllLinesAsync(Path.Join(artifacts, "plugin-libraries.txt"), modules, cancellationToken);
        if (aliases.Length == 0)
        {
            return;
        }

        int major = int.Parse(arguments[3], System.Globalization.CultureInfo.InvariantCulture);
        PostgresInstallation installation = string.IsNullOrEmpty(arguments[4])
            ? await PostgresInstallation.DiscoverAsync(major, cancellationToken)
            : await PostgresInstallation.CreateAsync(arguments[4], cancellationToken: cancellationToken);
        for (int index = 0; index < aliases.Length; index++)
        {
            string source = Path.Join(artifacts, "plugin-" + aliases[index] + ".c");
            await File.WriteAllTextAsync(source, Source(target), cancellationToken);
            (string compiler, List<string> compilerArguments) = await GetCompilerAsync(installation, arguments[5], arguments[6], arguments[7],
                source, Path.Join(output, modules[index]), Path.Join(artifacts, "plugin-" + aliases[index]), cancellationToken);
            await RunAsync(compiler, compilerArguments, cancellationToken);
            Console.WriteLine($"Ankus: built output plugin alias {modules[index]} for {library}.");
        }
    }

    /// <summary>
    /// Gets the C source of a module that forwards the output plugin entry point to <paramref name="library"/>.
    /// </summary>
    /// <param name="library">The extension library's name without its suffix, as PostgreSQL loads it.</param>
    /// <returns>The module's source.</returns>
    internal static string Source(string library) => $$"""
        /* Generated by Ankus. Loads the output plugin in "{{library}}" under this module's name, as pglogical's
         * pglogical_output module loads pglogical. */
        #include "postgres.h"
        #include "fmgr.h"
        #include "replication/output_plugin.h"

        PG_MODULE_MAGIC;

        extern PGDLLEXPORT void _PG_output_plugin_init(OutputPluginCallbacks *cb);

        void
        _PG_output_plugin_init(OutputPluginCallbacks *cb)
        {
            /* Casting through void (*)(void) marks the conversion as intended. */
            LogicalOutputPluginInit init = (LogicalOutputPluginInit) (void (*)(void))
                load_external_function("{{library}}", "_PG_output_plugin_init", true, NULL);
            init(cb);
        }

        """;

    private static async Task<(string Compiler, List<string> Arguments)> GetCompilerAsync(PostgresInstallation installation, string linker,
        string libraryDirectories, string triple, string source, string module, string intermediate, CancellationToken cancellationToken)
    {
        var arguments = new List<string>();
        if (OperatingSystem.IsWindows())
        {
            arguments.AddRange(["/nologo", "/std:c11", "/O2", "/MT", "/WX", "/utf-8", "/LD", $"/Fo{intermediate}.obj", $"/Fe{module}"]);
            arguments.Add($"/I{installation.ServerIncludeDirectory}");
            arguments.Add($"/I{installation.IncludeDirectory}");
            arguments.Add($"/I{Path.Join(installation.ServerIncludeDirectory, "port", "win32")}");
            arguments.Add($"/I{Path.Join(installation.ServerIncludeDirectory, "port", "win32_msvc")}");
            foreach (string directory in WindowsToolchain.GetIncludeDirectories(libraryDirectories))
            {
                arguments.Add($"/I{directory}");
            }

            string postgres = installation.TargetInfo?.MapPath(installation.LibraryDirectory) ?? installation.LibraryDirectory;
            arguments.AddRange([source, "/link", "/NOIMPLIB", "/NOEXP", Path.Join(postgres, "postgres.lib")]);
            foreach (string directory in libraryDirectories.Split(';', StringSplitOptions.RemoveEmptyEntries))
            {
                arguments.Add($"/LIBPATH:{directory.Trim()}");
            }

            return (Path.Join(Path.GetDirectoryName(linker) ?? string.Empty, "cl.exe"), arguments);
        }

        arguments.AddRange(await installation.GetPreprocessorArgumentsAsync(cancellationToken));
        if (!string.IsNullOrEmpty(triple))
        {
            arguments.Add($"--target={triple}");
        }

        arguments.AddRange(["-shared", "-fPIC", "-O2", "-Wall", "-Wextra", "-Werror"]);
        arguments.AddRange(["-isystem", installation.ServerIncludeDirectory, "-isystem", installation.IncludeDirectory]);
        if (OperatingSystem.IsMacOS())
        {
            // The backend supplies PostgreSQL's symbols when it loads the module, as for the extension's own library.
            arguments.Add("-Wl,-undefined,dynamic_lookup");
        }

        arguments.AddRange(["-o", module, source]);
        return (linker, arguments);
    }

    private static async Task RunAsync(string compiler, List<string> arguments, CancellationToken cancellationToken)
    {
        using var process = new Process { StartInfo = new ProcessStartInfo(compiler) { UseShellExecute = false } };
        foreach (string argument in arguments)
        {
            process.StartInfo.ArgumentList.Add(argument);
        }

        process.Start();
        await process.WaitForExitAsync(cancellationToken);
        if (process.ExitCode != 0)
        {
            throw new InvalidOperationException($"The compiler exited with code {process.ExitCode} building an output plugin alias.");
        }
    }

    [GeneratedRegex("^[A-Za-z0-9_+-][A-Za-z0-9._+-]*$")]
    private static partial Regex AliasName();
}
